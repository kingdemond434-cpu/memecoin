import {VersionedTransaction} from '@solana/web3.js';

const el = id => document.getElementById(id);
const from64 = s => Uint8Array.from(atob(s), c => c.charCodeAt(0));
const to64 = bytes => btoa(String.fromCharCode(...bytes));
let provider, address = '', paired = false;
async function api(path, data) {
  const response = await fetch('/api/' + path, {credentials: 'same-origin',
    method: data === undefined ? 'GET' : 'POST',
    headers: data === undefined ? {} : {'Content-Type': 'application/json'},
    body: data === undefined ? undefined : JSON.stringify(data)});
  if (!response.ok) throw new Error((await response.text()).slice(0, 220));
  return response.json();
}
function notice(message) { el('notice').textContent = message; }
async function disconnect() {
  address = '';
  await api('phantom/disconnect', {});
  el('wallet').textContent = 'No wallet connected.';
}
async function connect() {
  provider = window.phantom?.solana;
  if (!provider?.isPhantom) throw new Error('Install Phantom from phantom.com, then open this page in a top-level localhost browser tab.');
  if (!paired) throw new Error('Open the paired localhost link generated by the tunnel launcher.');
  const response = await provider.connect();
  const wallet = response.publicKey.toString();
  const challenge = await api('phantom/challenge', {address: wallet});
  const proof = await provider.signMessage(from64(challenge.message_base64), 'utf8');
  if (provider.publicKey.toString() !== wallet) throw new Error('Wallet changed during connection. Connect again.');
  await api('phantom/connect', {nonce: challenge.nonce, signature_base64: to64(proof.signature)});
  address = wallet;
  el('wallet').textContent = 'Connected: ' + address;
  provider.on('disconnect', () => disconnect().catch(e => notice(e.message)));
  provider.on('accountChanged', () => disconnect().catch(e => notice(e.message)));
  notice('Ownership verified. Trading remains subject to the server safety gates.');
}
async function approve(request) {
  if (!address || address !== request.address || provider?.publicKey?.toString() !== address)
    throw new Error('Reconnect the expected Phantom account before reviewing this request.');
  if (Date.now() / 1000 >= request.expires_at) throw new Error('This transaction request has expired.');
  const unsigned = from64(request.transaction_base64);
  const tx = VersionedTransaction.deserialize(unsigned);
  const hash = new Uint8Array(await crypto.subtle.digest('SHA-256', tx.message.serialize()));
  const hex = [...hash].map(b => b.toString(16).padStart(2, '0')).join('');
  if (hex !== request.message_sha256) throw new Error('Transaction message does not match the review request.');
  try {
    const signed = await provider.signTransaction(tx);
    await api('phantom/complete', {id: request.id, signed_transaction_base64: to64(signed.serialize())});
    notice('Signature returned to the execution engine. This page does not broadcast transactions.');
  } catch (error) {
    await api('phantom/complete', {id: request.id, reject: true}).catch(() => {});
    throw error;
  }
}
function button(text, action) {
  const node = document.createElement('button'); node.textContent = text;
  node.onclick = async () => {node.disabled = true; try {await action();} catch(e) {notice(e.message);} finally {node.disabled = false;}};
  return node;
}
async function refresh() {
  if (!paired) return;
  const status = await api('status');
  const data = status.prediction_markets;
  const research = status.public_wallet_research;
  if (research) {
    el('public-research').textContent = `${research.wallets} public wallets · ${research.trades} retained trades · ${research.forensic_reports} mechanism reports · ${research.public_claim_mentions} source/address links`;
    el('research-status').textContent = JSON.stringify({local_models: status.local_decisions, research_errors: research.source_errors}, null, 2);
  }
  el('mode').textContent = 'PAPER MODE · live submission locked · no real funds used';
  el('experiment').textContent = `Started ${new Date(data.started_at * 1000).toLocaleString()} · ${data.markets} markets · ${data.snapshots} retained book snapshots`;
  el('counts').textContent = `${JSON.stringify(data.order_counts)} · ${data.settlement_records} simulated settlements · ${data.real_fills} real fills`;
  el('errors').textContent = JSON.stringify(data.source_errors, null, 2);
  const rows = data.accounts.map(account => {
    const row = document.createElement('tr');
    for (const value of [account.id, account.cash, account.realized, account.open_positions]) {
      const cell = document.createElement('td'); cell.textContent = String(value); row.append(cell);
    }
    return row;
  });
  el('accounts').replaceChildren(...rows);
  const pending = (await api('phantom/requests')).requests;
  const cards = pending.map(request => {
    const card = document.createElement('div'); card.className = 'approval';
    const label = document.createElement('p'); label.textContent = `Wallet ${request.address} · expires ${new Date(request.expires_at * 1000).toLocaleTimeString()}`;
    const review = document.createElement('pre'); review.textContent = JSON.stringify(request.review, null, 2);
    card.append(label, review, button('Review in Phantom', () => approve(request)),
      button('Reject', () => api('phantom/complete', {id: request.id, reject: true})));
    return card;
  });
  if (cards.length) el('requests').replaceChildren(...cards);
  else el('requests').textContent = 'No pending requests.';
}
el('connect').onclick = () => connect().catch(e => notice(e.message));
el('disconnect').onclick = () => disconnect().then(() => provider?.disconnect()).catch(e => notice(e.message));
async function boot() {
  const fragment = new URLSearchParams(location.hash.slice(1));
  const token = fragment.get('pair');
  history.replaceState(null, '', location.pathname);
  if (token) await api('pair', {token});
  await api('status'); paired = true;
  await refresh();
}
boot().catch(e => notice('Pairing required: ' + e.message));
setInterval(() => refresh().catch(e => notice(e.message)), 5000);
